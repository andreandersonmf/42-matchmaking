const dictionaries: Record<Lang, Record<string, string>> = { en: {}, pt, es };

const TIERS: Record<Lang, Record<string, string>> = {
  en: {},
  pt: { Bronze: 'Bronze', Silver: 'Prata', Gold: 'Ouro', Platinum: 'Platina', Emerald: 'Esmeralda', Diamond: 'Diamante', Master: 'Mestre', Grandmaster: 'Grão-Mestre', Challenger: 'Desafiante' },
  es: { Bronze: 'Bronce', Silver: 'Plata', Gold: 'Oro', Platinum: 'Platino', Emerald: 'Esmeralda', Diamond: 'Diamante', Master: 'Maestro', Grandmaster: 'Gran Maestre', Challenger: 'Retador' },
};

export function translate(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  let text = dictionaries[lang][key] ?? key;
  for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
  return text;
}

export function rankName(lang: Lang, name: string): string {
  const space = name.lastIndexOf(' ');
  const tier = space === -1 ? name : name.slice(0, space);
  const numeral = space === -1 ? '' : name.slice(space + 1);
  const translated = TIERS[lang][tier] ?? tier;
  return numeral ? `${translated} ${numeral}` : translated;
}

export interface I18n {
  lang: Lang;
  setLang(lang: Lang): void;
  t(key: string, vars?: Record<string, string | number>): string;
  locale: string;
  number(value: number): string;
  date(value: number | null, time?: boolean): string;
  delta(value: number): string;
  rankName(name: string): string;
  modes: Record<MatchMode, string>;
  positions: Record<'spiker' | 'setter', string>;
  statuses: Record<MatchStatus, { label: string; tone: string }>;
}

function build(lang: Lang): Omit<I18n, 'lang' | 'setLang'> {
  const { locale } = LANGS.find(item => item.code === lang) ?? LANGS[0];
  const t = (key: string, vars: Record<string, string | number> = {}) => translate(lang, key, vars);
  const number = (value: number) => new Intl.NumberFormat(locale).format(Number.isFinite(value) ? value : 0);
  const date = (value: number | null, time = false) => value === null || !Number.isFinite(value) ? '—' : new Intl.DateTimeFormat(locale, { day: '2-digit', month: 'short', ...(time ? { hour: '2-digit', minute: '2-digit' } : {}) }).format(value);
  return {
    t,
    locale,
    number,
    date,
    delta: value => `${value > 0 ? '+' : ''}${number(value)}`,
    rankName: name => rankName(lang, name),
    modes: { captains: t('Captains'), balanced: t('Balanced'), random: t('Random') },
    positions: { spiker: t('Spiker'), setter: t('Setter') },
    statuses: {
      voting: { label: t('Mode voting'), tone: 'amber' }, captains: { label: t('Choosing captains'), tone: 'amber' }, drafting: { label: t('Team picking'), tone: 'amber' },
      ready: { label: t('Ready to play'), tone: 'blue' }, live: { label: t('Live'), tone: 'green' },
      mvp: { label: t('MVP voting'), tone: 'purple' }, completed: { label: t('Finished'), tone: 'neutral' }, cancelled: { label: t('Cancelled'), tone: 'neutral' },
    },
  };
}

const I18nContext = createContext<I18n>({ lang: 'en', setLang: () => {}, ...build('en') });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === 'en' || saved === 'pt' || saved === 'es') return saved;
    } catch { /* armazenamento indisponível */ }
    return 'en';
  });
  const setLang = (next: Lang) => {
    setLangState(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* armazenamento indisponível */ }
  };
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const value = useMemo<I18n>(() => ({ lang, setLang, ...build(lang) }), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);

export function LanguageSwitcher() {
  const { lang, setLang, t } = useI18n();
  return <div className="lang-switcher" role="group" aria-label={t('Language')}>
    {LANGS.map(({ code, flag, label }) => <button key={code} type="button" className={lang === code ? 'selected' : ''} aria-pressed={lang === code} title={label} onClick={() => setLang(code)}><span aria-hidden="true">{flag}</span><span className="sr-only">{label}</span></button>)}
  </div>;
}
